"""Write demand-shock variants of base env configs: configs/env/shocks/<base>__<preset>.yaml.

    python scripts/make_shock_configs.py configs/env/n1_k06.yaml configs/env/n5_k06.yaml
    python scripts/make_crn_paths.py configs/env/shocks/*.yaml

Each output is the base YAML plus a `scenario` (perinv.data.scenarios) and `shock_of: <base path>`. They are
eval-only: use them as `eval_envs` paired with the base config (configs/experiments/shocks.yaml).
Regenerate after any base config changes; the runner refuses a shock config whose base demand drifted.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from perinv.env.config import load_env_config
from perinv.utils.generated import publish

# Start windows assume the default horizon T = 30 (load_env_config re-checks them against each base config).
PRESETS: dict[str, list[dict]] = {
    "spike": [{"kind": "spike", "start": [7, 22], "duration": 3, "magnitude": 3.0}],          # 3-day promotion
    "drop": [{"kind": "drop", "start": [5, 20], "duration": 7, "magnitude": 0.4}],            # bad week
    "outage": [{"kind": "outage", "start": [5, 25], "duration": 2}],                          # store closed
    "shift": [{"kind": "drop", "start": [10, 15], "duration": 30, "magnitude": 0.6}],         # lasting fall
    "noisy": [{"kind": "overdispersed", "start": 0, "duration": 30, "magnitude": 0.5}],       # fat tails
}
HEADER = "# GENERATED by scripts/make_shock_configs.py. Do not edit by hand. Eval-only (perinv.data.scenarios).\n"


def write_variants(base_path: str | Path, out_dir: str | Path,
                   presets: dict[str, list[dict]] = PRESETS) -> tuple[list[Path], list[Path]]:
    """All variants of one base, validated before any is written; old variants of this base that are no longer
    presets are removed. Returns (written, removed)."""
    base_path = Path(base_path)
    raw = yaml.safe_load(base_path.read_text())
    if raw.get("scenario"):
        raise ValueError(f"{base_path} already has a scenario; pass a base config")
    files = {f"{base_path.stem}__{name}.yaml":
             yaml.safe_dump(raw | {"scenario": shocks, "shock_of": base_path.as_posix()},
                            sort_keys=False, default_flow_style=None)
             for name, shocks in presets.items()}
    return publish(files, out_dir, header=HEADER, validate=load_env_config,
                   owns=lambda p: p.name.startswith(f"{base_path.stem}__"))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("base_configs", nargs="+")
    ap.add_argument("--out", default="configs/env/shocks")
    args = ap.parse_args()
    for base in args.base_configs:
        written, removed = write_variants(base, args.out)
        for p in written:
            print(f"{base} -> {p.as_posix()}")
        for p in removed:
            print(f"removed stale {p.as_posix()}")


if __name__ == "__main__":
    main()
